  let rec aux acc ls = 
    match acc,ls with 
    |[],[]->[]
    |acc,[]-> acc
    |[],h::t->aux ((1,h)::[]) t
    |(n,x)::t1,h::t2-> if (x=h) then (aux ((n+1,x)::t1) t2) else (aux ([(1,h);(n,x)]@t1) t2)  
  in aux [(1,h)] t;;

