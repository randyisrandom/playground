type 'a node = One of 'a
  |Many of 'a node list



let flatten (ls: 'a node list) : 'a list = 
  let rec aux (acc: 'a list)  = function 
    []->[]
    |h :: t -> 
      begin 
        match 
        h with One x -> aux (x::acc) t
        |Many x -> aux acc x end 
  in aux [] ls

